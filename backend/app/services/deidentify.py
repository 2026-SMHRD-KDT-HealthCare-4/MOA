"""
챗봇 대화 텍스트 비식별화 — 요구사항 13번 (이름 제외 버전)

CHAT_SESSION.messages 에 적재되는 대화 텍스트에서 생년월일, 주소, 전화번호를
정규식 기반으로 탐지해 [MASK] 토큰으로 치환한다.

※ 이름은 비식별화 대상에서 제외한다.
  정규식만으로는 한글 이름과 일반 명사를 안정적으로 구분할 수 없어 오탐(평범한 단어
  마스킹)과 미탐(호칭 없는 이름 누락)이 모두 발생하기 때문이다. 안부 대화 특성상
  이름이 그대로 남아도 단독으로는 식별력이 낮다고 판단하여 제외한다. 향후 이름까지
  비식별화가 필요하면 NER(개체명 인식) 모델을 도입해 이 모듈을 보강하면 된다.

  반면 생년월일/주소/전화번호는 형식이 뚜렷해 정규식으로 정확히 탐지 가능하며,
  단독으로도 식별력이 높아 우선 마스킹 대상으로 둔다.
"""

import re

MASK = "[MASK]"

# 전화번호: 010-1234-5678, 02-123-4567, 01012345678 등
# (?<!\d), (?!\d) 로 앞뒤에 숫자가 더 붙어있지 않은 경우만 매칭 (긴 숫자열 일부 오매칭 방지)
_PHONE_RE = re.compile(r"(?<!\d)0\d{1,2}[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)")

# 생년월일: 1990-01-01, 1990.1.1, 1990년 1월 1일 등
_BIRTHDATE_RE = re.compile(r"(?:19|20)\d{2}[-./년]\s?\d{1,2}[-./월]\s?\d{1,2}일?")

# 주소: "OO시/도 OO구/군 OO동/로/길 OO번지/호" 패턴의 핵심 키워드 기반 탐지
_ADDRESS_RE = re.compile(
    r"[가-힣]{2,10}(?:특별시|광역시|도|시|군|구)\s?[가-힣0-9]{2,15}(?:동|로|길|읍|면)\s?[0-9\-]{1,10}(?:번지|호)?"
)


def deidentify(text: str) -> str:
    """대화 텍스트에서 생년월일/주소/전화번호를 [MASK] 로 치환한다. (이름은 보존)"""
    if not text:
        return text

    masked = text
    masked = _PHONE_RE.sub(MASK, masked)
    masked = _BIRTHDATE_RE.sub(MASK, masked)
    masked = _ADDRESS_RE.sub(MASK, masked)

    return masked
